  "(function (root) {\n'use strict';\nconst C01P_ART = root.LIV_ART_C01P;\n" + body +
  "\nroot.LIV = { " + names.split(" ").join(", ") + " };\n})(typeof window !== 'undefined' ? window : globalThis);\n";
