// Write the A1–B1 table of contents into grammatik/grammatik.js from tools/grammar-a1b1/order.json
// and the private chapter data (titles, kickers, levels). Chapter IDs never change, so saved results,
// assignments and links survive; only order, names and the displayed chapter number change.
// Usage: node tools/grammar-a1b1/catalog.cjs
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../..'), dir = path.join(root, '.local/grammar-a1b1');
const order = JSON.parse(fs.readFileSync(path.join(__dirname, 'order.json'), 'utf8'));
const pad = n => String(n).padStart(3, '0');
const ids = order.groups.flatMap(g => g.ch);
assert.deepEqual([...ids].sort((a, b) => a - b), Array.from({ length: 85 }, (_, i) => i + 1), 'order.json must list chapters 1–85 exactly once');
const no = {}; ids.forEach((n, i) => no[n] = i + 1);
const q = s => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const lines = order.groups.map(g => {
  const ch = g.ch.map(n => { const c = JSON.parse(fs.readFileSync(path.join(dir, 'chapters', pad(n) + '.json'), 'utf8')); return `[${n}, ${q(c.title)}, ${q(c.kicker)}, ${q(c.level)}]`; });
  return `  { t: ${q(g.t)}, ic: ${q(g.ic)}, h: ${g.h}${g.open ? ', open: true' : ''}, ch: [\n    ${ch.join(',\n    ')} ] },`;
});
const file = path.join(root, 'grammatik/grammatik.js'); let s = fs.readFileSync(file, 'utf8');
const START = '  /* A1–B1: generated by tools/grammar-a1b1/catalog.cjs */', END = '  /* end A1–B1 */';
let a = s.indexOf(START), b;
if (a >= 0) b = s.indexOf(END) + END.length;
else { a = s.search(/\n  \{ t: 'Verben 1'/) + 1; b = s.indexOf('  /* B2–C1:'); }
assert.ok(a > 0 && b > a, 'cannot find the A1–B1 section');
s = s.slice(0, a) + START + '\n' + lines.join('\n') + '\n' + END + (s[b] === '\n' ? '' : '\n') + s.slice(b).replace(/^\n?/, '\n');
// displayed chapter numbers follow the learning order
const NO = 'const A1B1_NO = ' + JSON.stringify(no) + ';';
s = /const A1B1_NO = [^;]*;/.test(s) ? s.replace(/const A1B1_NO = [^;]*;/, NO) : s.replace(/const SOURCE_NO = /, NO + '\nconst SOURCE_NO = ');
s = s.replace(/const gNo = n => [^;]*;/, 'const gNo = n => A1B1_NO[n] || SOURCE_NO[n] || n;');
// appendix: ordinal numbers reference unit 106 next to the other A1–B1 lists
if (!s.includes('[106,"Ordinalzahlen und Datum"')) s = s.replace('[104,"Verben mit Präpositionen","warten auf, denken an … – mit Trainer","Liste"]', '[104,"Verben mit Präpositionen","warten auf, denken an … – mit Trainer","Liste"],[106,"Ordinalzahlen und Datum","der erste, am zweiten Mai – mit Trainer","Liste"]');
if (!s.includes('101, 102, 103, 104, 106,')) s = s.replace('101, 102, 103, 104, 201', '101, 102, 103, 104, 106, 201');
fs.writeFileSync(file, s);
fs.writeFileSync(path.join(dir, 'groups.json'), JSON.stringify(Object.fromEntries(order.groups.flatMap(g => g.ch.map(n => [n, g.t]))), null, 1));
console.log('Wrote ' + order.groups.length + ' A1–B1 groups (' + ids.length + ' chapters) and display numbers.');
