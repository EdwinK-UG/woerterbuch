const fs = require("node:fs");
const crypto = require("node:crypto");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const hash = (text) =>
  crypto.createHash("sha256").update(text).digest("hex").slice(0, 12);
const files = [
  "config.js",
  "konto.js",
  "js/course-mail.js",
  "js/course-counts.js",
  "js/study-sync.js",
  "js/game-messages.js",
  "js/game-i18n.js",
  "js/render-safety.js",
  "js/dictionary-english.js",
  "js/site-design.js",
  "content/dictionary-english.json",
  "js/pages.js",
  "js/email-verification.js",
  "grammatik/catalog.js",
  "grammatik/grammatik.js",
  "grammatik/illustrations.js",
  "grammatik/motion.js",
  "grammatik/watch.js",
  "grammatik/film-stage.js",
  "grammatik/film-props.js",
  "grammatik/film-park.js",
  "grammatik/liv/liv-art.js",
  "grammatik/liv/engine.js",
  "grammatik/liv/film-park.js",
  "grammatik/film.js",
  "grammatik/film.css",
  "grammatik/vocabulary.js",
  "grammatik/vocabulary-art.js",
  "grammatik/vocabulary.css",
];
let index = read("index.html");
for (const file of ["core.bin", "defs.bin"]) {
  index = index.replace(new RegExp(file.replace(".", "\\.") + "\\?v=[a-zA-Z0-9]+", "g"),
    file + "?v=" + hash(fs.readFileSync(path.join(root, file))));
}
for (const file of files) {
  const escaped = file.replace(/[.*+?^$\{\}()|[\]\\]/g, "\\$&");
  index = index.replace(
    new RegExp(escaped + "\\?v=[a-zA-Z0-9]+", "g"),
    file + "?v=" + hash(read(file)),
  );
}
const version = hash(index + files.map((file) => hash(read(file))).join(""));
const shell = [
  "./",
  ...files
    .filter((file) => !file.startsWith("grammatik/"))
    .map((file) => file + "?v=" + hash(read(file))),
  "icon-64.png?v=2",
  "favicon.svg?v=3",
];
const release =
  "// Generated by tools/version-assets.cjs\nconst SHELL_RELEASE = " +
  JSON.stringify(version) +
  ";\nconst SHELL_ASSETS = " +
  JSON.stringify(shell, null, 2) +
  ";\n";
if (process.argv.includes("--check")) {
  if (index !== read("index.html") || release !== read("release.js"))
    throw Error("Asset versions are stale. Run npm run assets.");
} else {
  fs.writeFileSync(path.join(root, "index.html"), index);
  fs.writeFileSync(path.join(root, "release.js"), release);
}
