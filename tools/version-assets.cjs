const fs = require("node:fs");
const crypto = require("node:crypto");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const hash = (text) =>
  crypto.createHash("sha256").update(text).digest("hex").slice(0, 12);
const files = [
  "config.js",
  "konto.js",
  "js/course-mail.js",
  "js/course-counts.js",
  "js/study-sync.js",
  "js/game-messages.js",
  "js/game-i18n.js",
  "js/render-safety.js",
  "js/dictionary-english.js",
  "js/lesson-help.js",
  "js/site-design.js",
  "content/dictionary-english.json",
  "js/pages.js",
  "js/email-verification.js",
  "grammatik/catalog.js",
  "grammatik/grammatik.js",
  "grammatik/illustrations.js",
  "grammatik/motion.js",
  "grammatik/watch.js",
  "grammatik/film-stage.js",
  "grammatik/film-props.js",
  "grammatik/film-park.js",
  "grammatik/liv/liv-art.js",
  "grammatik/liv/engine.js",
  "grammatik/liv/film-park.js",
  "grammatik/liv/film-park-3d.js",
  "grammatik/liv/liv.vrm",
  "grammatik/film.js",
  "grammatik/film.css",
  "grammatik/vocabulary.js",
  "grammatik/vocabulary-art.js",
  "grammatik/vocabulary.css",
];
let index = read("index.html");
for (const file of ["core.bin", "defs.bin"]) {
  index = index.replace(new RegExp(file.replace(".", "\\.") + "\\?v=[a-zA-Z0-9]+", "g"),
    file + "?v=" + hash(fs.readFileSync(path.join(root, file))));
}
// Pre-translated English: one version for all 256 files, from their combined contents.
{
  const dir = path.join(root, "content/english");
  const shards = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /^[0-9a-f]{2}\.json$/.test(f)).sort() : [];
  const combined = hash(shards.map((f) => f + hash(fs.readFileSync(path.join(dir, f)))).join(""));
  index = index.replace(/content\/english\/\{xx\}\.json\?v=[a-zA-Z0-9]+/g, "content/english/{xx}.json?v=" + combined);
}
for (const file of files) {
  const escaped = file.replace(/[.*+?^$\{\}()|[\]\\]/g, "\\$&");
  index = index.replace(
    new RegExp(escaped + "\\?v=[a-zA-Z0-9]+", "g"),
    file + "?v=" + hash(read(file)),
  );
}
// Brand artwork is versioned by hand (?v=7); its bytes still roll the release so a new
// icon or logo always replaces the offline copies.
const brandFiles = [
  "favicon.svg", "favicon.ico", "icon-32.png", "icon-64.png", "icon-180.png", "icon-192.png", "icon-512.png",
  "site.webmanifest", "assets/brand/brand.css", "assets/brand/logo-horizontal-mixed.svg",
  "assets/brand/logo-horizontal-mixed-dark.svg", "assets/brand/logo-mark.svg",
];
const version = hash(
  index +
    files.map((file) => hash(read(file))).join("") +
    brandFiles.map((file) => hash(fs.readFileSync(path.join(root, file)))).join(""),
);
const shell = [
  "./",
  ...files
    .filter((file) => !file.startsWith("grammatik/"))
    .map((file) => file + "?v=" + hash(read(file))),
  "favicon.svg?v=7",
  "icon-180.png?v=7",
  "site.webmanifest?v=7",
  "assets/brand/brand.css?v=7",
  "assets/brand/logo-horizontal-mixed.svg",
  "assets/brand/logo-horizontal-mixed-dark.svg",
  "assets/brand/logo-mark.svg",
];
const release =
  "// Generated by tools/version-assets.cjs\nconst SHELL_RELEASE = " +
  JSON.stringify(version) +
  ";\nconst SHELL_ASSETS = " +
  JSON.stringify(shell, null, 2) +
  ";\n";
if (process.argv.includes("--check")) {
  if (index !== read("index.html") || release !== read("release.js"))
    throw Error("Asset versions are stale. Run npm run assets.");
} else {
  fs.writeFileSync(path.join(root, "index.html"), index);
  fs.writeFileSync(path.join(root, "release.js"), release);
}
